/** মুদ্রা: ৳১,২৩,৪৫৬.৭৫ স্টাইল (বাংলাদেশি গ্রুপিং, ইংরেজি সংখ্যা) */
export function money(poisha: number | null | undefined, opts?: { symbol?: boolean; decimals?: boolean }): string {
  const v = (poisha ?? 0) / 100
  const neg = v < 0
  const abs = Math.abs(v)
  const showDec = opts?.decimals ?? true
  const s = abs.toLocaleString('en-IN', {
    minimumFractionDigits: showDec ? 2 : 0,
    maximumFractionDigits: showDec ? 2 : 0
  })
  return `${neg ? '-' : ''}${opts?.symbol === false ? '' : '৳'}${s}`
}

export function num(v: number | null | undefined, decimals = 0): string {
  return (v ?? 0).toLocaleString('en-IN', { minimumFractionDigits: decimals, maximumFractionDigits: 3 })
}

const BN_MONTHS = ['জানু', 'ফেব', 'মার্চ', 'এপ্রিল', 'মে', 'জুন', 'জুলাই', 'আগস্ট', 'সেপ্ট', 'অক্টো', 'নভে', 'ডিসে']

export function fdate(ms: number | null | undefined): string {
  if (!ms) return '—'
  const d = new Date(ms)
  return `${d.getDate()} ${BN_MONTHS[d.getMonth()]} ${d.getFullYear()}`
}

export function fdatetime(ms: number | null | undefined): string {
  if (!ms) return '—'
  const d = new Date(ms)
  const hh = d.getHours()
  const mm = String(d.getMinutes()).padStart(2, '0')
  const ampm = hh < 12 ? 'AM' : 'PM'
  const h12 = hh % 12 === 0 ? 12 : hh % 12
  return `${fdate(ms)} ${h12}:${mm} ${ampm}`
}

export function ftime(ms: number | null | undefined): string {
  if (!ms) return '—'
  const d = new Date(ms)
  const hh = d.getHours()
  const mm = String(d.getMinutes()).padStart(2, '0')
  const ampm = hh < 12 ? 'AM' : 'PM'
  const h12 = hh % 12 === 0 ? 12 : hh % 12
  return `${h12}:${mm} ${ampm}`
}

/** yyyy-mm-dd for <input type="date"> */
export function dateInput(ms: number | null | undefined): string {
  if (!ms) return ''
  const d = new Date(ms)
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`
}

export function dateInputToMs(v: string, endOfDay = false): number {
  if (!v) return endOfDay ? Date.now() : Date.now()
  const [y, m, d] = v.split('-').map(Number)
  return endOfDay ? new Date(y, m - 1, d, 23, 59, 59, 999).getTime() : new Date(y, m - 1, d, 0, 0, 0, 0).getTime()
}

/** পরিসর প্রিসেট — ms */
export function presetRange(kind: string): { from: number; to: number } {
  const now = new Date()
  const end = now.getTime()
  const startOfToday = new Date(now.getFullYear(), now.getMonth(), now.getDate()).getTime()
  switch (kind) {
    case 'today': return { from: startOfToday, to: end }
    case 'yesterday': return { from: startOfToday - 86_400_000, to: startOfToday - 1 }
    case '7d': return { from: startOfToday - 6 * 86_400_000, to: end }
    case '30d': return { from: startOfToday - 29 * 86_400_000, to: end }
    case 'month': return { from: new Date(now.getFullYear(), now.getMonth(), 1).getTime(), to: end }
    case '3m': return { from: new Date(now.getFullYear(), now.getMonth() - 2, 1).getTime(), to: end }
    case '6m': return { from: new Date(now.getFullYear(), now.getMonth() - 5, 1).getTime(), to: end }
    case '1y': return { from: new Date(now.getFullYear() - 1, now.getMonth(), now.getDate()).getTime(), to: end }
    default: return { from: startOfToday - 6 * 86_400_000, to: end }
  }
}

export function bnPhone(v: string): string {
  const digits = v.replace(/\D/g, '')
  if (digits.length === 11) return `${digits.slice(0, 5)} ${digits.slice(5, 8)} ${digits.slice(8)}`
  return v
}
